import {
  jalaliMonthLength,
  jalaliWeekday,
  startOfTehranDay,
  toJalali,
  zonedJalaliToDate,
} from '../../lib/jalali';

export type JalaliMonth = { year: number; month: number };
export type CalendarReminderDate = { due_at: string | null };

export type JalaliCalendarCell = {
  key: string;
  day: number | null;
  count: number;
  isToday: boolean;
};

const pad = (value: number) => String(value).padStart(2, '0');
export const jalaliMonthKey = ({ year, month }: JalaliMonth) => `${year}-${pad(month)}`;
export const jalaliDayKey = (year: number, month: number, day: number) =>
  `${year}-${pad(month)}-${pad(day)}`;

export function readJalaliMonth(value: string | null | undefined, now = new Date()): JalaliMonth {
  const fallback = toJalali(now);
  if (!value || !/^\d{4}-\d{2}$/.test(value)) return { year: fallback.year, month: fallback.month };
  const [year, month] = value.split('-').map(Number);
  try {
    if (!Number.isInteger(year) || year < 1 || year > 3175 || !Number.isInteger(month) || month < 1 || month > 12) {
      return { year: fallback.year, month: fallback.month };
    }
    jalaliMonthLength(year, month);
    return { year, month };
  } catch {
    return { year: fallback.year, month: fallback.month };
  }
}

export function shiftJalaliMonth(value: JalaliMonth, delta: number): JalaliMonth {
  if (!Number.isInteger(delta)) throw new RangeError('تغییر ماه باید عدد صحیح باشد');
  const absolute = value.year * 12 + (value.month - 1) + delta;
  const year = Math.floor(absolute / 12);
  const month = ((absolute % 12) + 12) % 12 + 1;
  if (year < 1 || year > 3175) return value;
  return { year, month };
}

/**
 * Accepts Jalali day keys generated by the month calendar and legacy Gregorian
 * day keys created by the first phase, returning Tehran midnight in both cases.
 */
export function parseReminderDayKey(value: string | null | undefined): Date | null {
  if (!value || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return null;
  const [year, month, day] = value.split('-').map(Number);
  try {
    if (year >= 1700) {
      const parsed = new Date(`${value}T12:00:00+03:30`);
      if (!Number.isFinite(parsed.getTime())) return null;
      const tehranDay = startOfTehranDay(parsed);
      const parts = new Intl.DateTimeFormat('en-CA', {
        timeZone: 'Asia/Tehran',
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
      }).formatToParts(tehranDay);
      const part = (type: string) => parts.find((entry) => entry.type === type)?.value ?? '';
      return `${part('year')}-${part('month')}-${part('day')}` === value ? tehranDay : null;
    }
    if (!Number.isInteger(year) || !Number.isInteger(month) || !Number.isInteger(day)) return null;
    const parsed = zonedJalaliToDate(year, month, day, 0, 0, 0);
    const actual = toJalali(parsed);
    return actual.year === year && actual.month === month && actual.day === day ? parsed : null;
  } catch {
    return null;
  }
}

export function buildJalaliMonthGrid(
  year: number,
  month: number,
  reminders: readonly CalendarReminderDate[],
  now = new Date(),
): JalaliCalendarCell[] {
  const length = jalaliMonthLength(year, month);
  const firstDay = zonedJalaliToDate(year, month, 1, 12, 0, 0);
  const leadingCells = jalaliWeekday(firstDay);
  const today = toJalali(now);
  const counts = new Map<string, number>();

  for (const reminder of reminders) {
    if (!reminder.due_at) continue;
    const due = new Date(reminder.due_at);
    if (!Number.isFinite(due.getTime())) continue;
    const date = toJalali(due);
    if (date.year !== year || date.month !== month) continue;
    const key = jalaliDayKey(date.year, date.month, date.day);
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }

  const totalCells = Math.ceil((leadingCells + length) / 7) * 7;
  return Array.from({ length: totalCells }, (_, index) => {
    const day = index - leadingCells + 1;
    if (day < 1 || day > length) {
      return { key: `blank-${index}`, day: null, count: 0, isToday: false };
    }
    const key = jalaliDayKey(year, month, day);
    return {
      key,
      day,
      count: counts.get(key) ?? 0,
      isToday: today.year === year && today.month === month && today.day === day,
    };
  });
}

